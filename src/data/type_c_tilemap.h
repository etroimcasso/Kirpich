// The Type C gameplay backdrop: the panel a rising-floor round plays against.
//
// Type C carries four readouts - a score, a level, the countdown to the next rise, and a line count -
// where the two stored gameplay screens each carry three and have room for exactly three. So this
// screen is the port's own, built from the same tile vocabulary the stored ones use: the same box
// corners, edges and sides, the same font, the same field walls, and the next-piece box copied cell
// for cell so the preview sprite lands where it does on the other two.
//
// The panel, in columns 13 to 19:
//
//     rows 0-3    the score box - label, then six digits on an open row, as Type A draws them
//     rows 4-11   one box holding LEVEL, RISE and LINES, each a label above its value
//     rows 12-17  the next-piece box, identical to both stored screens
//
// LINES sits on the rows every gameplay screen puts it on, so it reads in the same place whichever
// mode is running - and so printLines, printLinesSeed and copyLinesToSecondMap need no Type C case.
// LEVEL and RISE share a section with no dividing line between them: the twelve rows above the
// preview box hold four labels, four value rows, two borders and two dividers exactly.
//
// Columns 0 to 12 are the playing field and its walls, identical to the stored gameplay screens - the
// left border column, the three-tile wall pattern that cycles every third row, and ten columns of
// space that the board is drawn over.
//
// Where each readout writes is in src/systems/readouts.cpp, beside the cells for the other two modes.

